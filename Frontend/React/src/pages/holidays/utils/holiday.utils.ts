// ============================================================
// DATE PARSING
// ============================================================

/**
 * Supports both:
 *
 * API format:
 *     2026-09-14
 *
 * Display format:
 *     14 Sep 2026
 *
 * Display format generated by Intl:
 *     14 Sept 2026
 *
 * The function always returns a LOCAL Date object.
 */
const parseHolidayDate = (
  dateValue: string,
): Date => {

  if (
    typeof dateValue !==
      "string" ||
    !dateValue.trim()
  ) {

    throw new Error(
      "Invalid holiday date received from API.",
    );
  }


  const value =
    dateValue.trim();


  // ==========================================================
  // FORMAT 1: YYYY-MM-DD
  // ==========================================================

  const isoMatch =
    value.match(
      /^(\d{4})-(\d{1,2})-(\d{1,2})$/,
    );


  if (isoMatch) {

    const year =
      Number(
        isoMatch[1],
      );

    const month =
      Number(
        isoMatch[2],
      );

    const day =
      Number(
        isoMatch[3],
      );


    return createValidatedDate(
      year,
      month - 1,
      day,
      value,
    );
  }


  // ==========================================================
  // FORMAT 2: DD MON YYYY
  //
  // Examples:
  //
  // 14 Sep 2026
  // 14 Sept 2026
  // 14 September 2026
  // ==========================================================

  const displayMatch =
    value.match(
      /^(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})$/,
    );


  if (displayMatch) {

    const day =
      Number(
        displayMatch[1],
      );

    const monthName =
      displayMatch[2]
        .toLowerCase();

    const year =
      Number(
        displayMatch[3],
      );


    const month =
      MONTH_MAP[
        monthName
      ];


    if (
      month !==
      undefined
    ) {

      return createValidatedDate(
        year,
        month,
        day,
        value,
      );
    }
  }


  // ==========================================================
  // INVALID
  // ==========================================================

  throw new Error(
    `Invalid holiday date received from API: ${dateValue}`,
  );
};


// ============================================================
// CREATE + VALIDATE DATE
// ============================================================

const createValidatedDate = (
  year: number,
  monthIndex: number,
  day: number,
  originalValue: string,
): Date => {

  const date =
    new Date(
      year,
      monthIndex,
      day,
    );


  /*
   * JavaScript automatically rolls invalid dates:
   *
   * new Date(2026, 1, 31)
   *
   * can become a March date.
   *
   * Therefore validate every component.
   */

  if (
    date.getFullYear() !==
      year ||
    date.getMonth() !==
      monthIndex ||
    date.getDate() !==
      day
  ) {

    throw new Error(
      `Invalid holiday date received from API: ${originalValue}`,
    );
  }


  return date;
};


// ============================================================
// DATE DISPLAY
// ============================================================

export const formatDateDisplay = (
  dateValue: string,
): string => {

  const date =
    parseHolidayDate(
      dateValue,
    );


  return new Intl.DateTimeFormat(
    "en-GB",
    {
      day: "2-digit",
      month: "short",
      year: "numeric",
    },
  ).format(date);
};


// ============================================================
// DAY NAME
// ============================================================

export const getDayName = (
  dateValue: string,
): string => {

  const date =
    parseHolidayDate(
      dateValue,
    );


  return new Intl.DateTimeFormat(
    "en-US",
    {
      weekday: "long",
    },
  ).format(date);
};


// ============================================================
// DAY VARIANT
// ============================================================

export const getDayVariant = (
  dateValue: string,
): Holiday["dayVariant"] => {

  const day =
    getDayName(
      dateValue,
    ).toLowerCase();


  if (
    SUPPORTED_DAY_VARIANTS.includes(
      day as Holiday["dayVariant"],
    )
  ) {

    return day as Holiday["dayVariant"];
  }


  return "monday";
};


