// ============================================================
// API → UI MAPPING
// ============================================================

export const mapHolidayFromApi = (
  holiday: HolidayApiResponse,
): Holiday => {

  if (
    holiday.id ===
      null ||
    holiday.id ===
      undefined
  ) {

    throw new Error(
      "Holiday API returned an invalid holiday ID.",
    );
  }


  if (
    !holiday.holiday_name ||
    !holiday.holiday_name.trim()
  ) {

    throw new Error(
      "Holiday API returned an invalid holiday name.",
    );
  }


  /*
   * Validate the API date.
   *
   * Important:
   * The API sends YYYY-MM-DD.
   */

  const holidayDate =
    parseHolidayDate(
      holiday.holiday_date,
    );


  return {

    id:
      String(
        holiday.id,
      ),

    title:
      holiday.holiday_name,

    /*
     * UI display value.
     *
     * Example:
     *
     * 14 Sept 2026
     */

    date:
      formatDateDisplay(
        holiday.holiday_date,
      ),

    day:
      new Intl.DateTimeFormat(
        "en-US",
        {
          weekday: "long",
        },
      ).format(
        holidayDate,
      ),

    icon:
      getHolidayIcon(
        holiday.holiday_name,
      ),

    dayVariant:
      getDayVariant(
        holiday.holiday_date,
      ),

    /*
     * Backend:
     *
     * 1 = Active
     * 0 = Inactive
     */

    status:
      holiday.status,
  };
};


// ============================================================
// DISPLAY DATE → LOCAL DATE
// ============================================================

const parseDisplayDate = (
  displayDate: string,
): Date => {

  return parseHolidayDate(
    displayDate,
  );
};


// ============================================================
// STATISTICS
// ============================================================

export const calculateStatistics = (
  holidays: Holiday[],
): {
  totalHolidays: number;

  upcomingHolidays: number;

  nextUpcomingHoliday: Holiday | null;

  longWeekends: number;

  observedHolidays: number;
} => {

  /*
   * Backend status:
   *
   * 1 = Active
   * 0 = Inactive
   */
  const activeHolidays =
    holidays.filter(
      (holiday) =>
        holiday.status === 1,
    );


  // ==========================================================
  // TOTAL ACTIVE HOLIDAYS
  // ==========================================================

  const total =
    activeHolidays.length;


  // ==========================================================
  // TODAY
  // ==========================================================

  const today =
    new Date();

  today.setHours(
    0,
    0,
    0,
    0,
  );


  // ==========================================================
  // UPCOMING HOLIDAYS
  //
  // Includes:
  // - Today's holiday
  // - Future holidays
  //
  // Excludes:
  // - Past holidays
  // ==========================================================

  const upcomingHolidayList =
    activeHolidays
      .filter(
        (holiday) => {

          const holidayDate =
            parseDisplayDate(
              holiday.date,
            );

          holidayDate.setHours(
            0,
            0,
            0,
            0,
          );

          return (
            holidayDate.getTime() >=
            today.getTime()
          );
        },
      )
      .sort(
        (
          first,
          second,
        ) => {

          const firstDate =
            parseDisplayDate(
              first.date,
            );

          const secondDate =
            parseDisplayDate(
              second.date,
            );

          return (
            firstDate.getTime() -
            secondDate.getTime()
          );
        },
      );


  // ==========================================================
  // NEXT UPCOMING HOLIDAY
  //
  // The first item after sorting is always the
  // nearest upcoming holiday.
  // ==========================================================

  const nextUpcomingHoliday =
    upcomingHolidayList.length > 0
      ? upcomingHolidayList[0]
      : null;


  // ==========================================================
  // LONG WEEKENDS
  // ==========================================================

  const longWeekends =
    calculateLongWeekends(
      activeHolidays,
    );


  // ==========================================================
  // RETURN
  // ==========================================================

  return {

    totalHolidays:
      total,

    upcomingHolidays:
      upcomingHolidayList.length,

    nextUpcomingHoliday,

    longWeekends,

    /*
     * Preserve your existing UI behavior.
     */
    observedHolidays:
      total,
  };
};


// ============================================================
// LONG WEEKEND CALCULATION
// ============================================================

const calculateLongWeekends = (
  holidays: Holiday[],
): number => {

  if (
    holidays.length === 0
  ) {

    return 0;
  }


  const sortedDates =
    holidays
      .map(
        (
          holiday,
        ) =>
          parseDisplayDate(
            holiday.date,
          ),
      )
      .sort(
        (
          firstDate,
          secondDate,
        ) =>
          firstDate.getTime() -
          secondDate.getTime(),
      );


  let longWeekendCount =
    0;


  for (
    let index = 0;
    index <
    sortedDates.length;
    index++
  ) {

    const date =
      sortedDates[index];


    const day =
      date.getDay();


    const previousDate =
      index > 0
        ? sortedDates[
            index - 1
          ]
        : null;


    const nextDate =
      index <
      sortedDates.length - 1
        ? sortedDates[
            index + 1
          ]
        : null;


    const hasPreviousHoliday =
      previousDate !== null &&
      differenceInDays(
        previousDate,
        date,
      ) === 1;


    const hasNextHoliday =
      nextDate !== null &&
      differenceInDays(
        date,
        nextDate,
      ) === 1;


    /*
     * Monday + Tuesday
     */
    const mondayTuesday =
      day === 1 &&
      hasNextHoliday;


    /*
     * Friday + Saturday
     */
    const fridaySaturday =
      day === 5 &&
      hasPreviousHoliday;


    /*
     * Saturday + Sunday
     */
    const saturdaySunday =
      day === 6 &&
      hasPreviousHoliday;


    /*
     * Sunday + Monday
     */
    const sundayMonday =
      day === 0 &&
      hasNextHoliday;


    if (
      mondayTuesday ||
      fridaySaturday ||
      saturdaySunday ||
      sundayMonday
    ) {

      longWeekendCount++;
    }
  }


  return Math.floor(
    longWeekendCount / 2,
  );
};


// ============================================================
// DATE DIFFERENCE
// ============================================================

const differenceInDays = (
  firstDate: Date,
  secondDate: Date,
): number => {

  const millisecondsPerDay =
    1000 *
    60 *
    60 *
    24;


  return Math.round(
    Math.abs(
      firstDate.getTime() -
      secondDate.getTime(),
    ) /
      millisecondsPerDay,
  );
};