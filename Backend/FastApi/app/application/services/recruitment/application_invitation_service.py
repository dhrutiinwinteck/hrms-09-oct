import hashlib
import secrets
from datetime import datetime, timedelta

from sqlalchemy.orm import Session

from app.application.dtos.recruitment.application_invitation import (
    ApplicationInvitationEmailTemplateResponse,
    ApplicationInvitationResponse,
    ApplicationInvitationValidationResponse,
    CreateApplicationInvitationRequest,
)
from app.infrastructure.email.email_service import EmailService
from app.core.config import settings
from app.infrastructure.models.recruitment.application_invitation import (
    ApplicationInvitation,
    ApplicationInvitationStatus,
)
from app.infrastructure.repositories.recruitment.application_invitation_repository import (
    ApplicationInvitationRepository,
)


class ApplicationInvitationService:

    DEFAULT_SUBJECT = (
        "Invitation to Complete Application Form – "
        "Inwinteck Private Limited"
    )

    DEFAULT_MESSAGE = """Dear Candidate,

Greetings from Inwinteck Private Limited!

We are pleased to invite you to complete our candidate application form as the next step in our recruitment process.

Please use the following link to access and complete the application form:

Application Form:

{{APPLICATION_LINK}}

Kindly ensure that all the information provided is accurate and complete. Once submitted, your application will be reviewed by our HR team, and you will be contacted regarding the next steps in the selection process.

We appreciate your time and interest in pursuing an opportunity with Inwinteck Technologies.

Best Regards,

HR Team
Inwinteck Private Limited
"""

    def __init__(self, session: Session) -> None:
        self.session = session

        self.repository = ApplicationInvitationRepository(
            session
        )

        self.email_service = EmailService()

    # ============================================================
    # EMAIL TEMPLATE
    # ============================================================

    def get_email_template(
        self,
    ) -> ApplicationInvitationEmailTemplateResponse:
        """
        Returns the backend default email template.

        Frontend can load this template and allow the employee
        to edit it before submitting.
        """

        message = self.DEFAULT_MESSAGE.replace(
            "{{EXPIRY_DAYS}}",
            str(
                settings.APPLICATION_INVITATION_EXPIRY_DAYS
            ),
        )

        return ApplicationInvitationEmailTemplateResponse(
            subject=self.DEFAULT_SUBJECT,
            message=message,
        )

    # ============================================================
    # CREATE INVITATION
    # ============================================================

    async def create_invitation(
        self,
        request: CreateApplicationInvitationRequest,
        sent_by_employee_id: int,
    ) -> ApplicationInvitationResponse:

        if sent_by_employee_id <= 0:
            raise ValueError(
                "Authenticated employee ID is invalid."
            )

        # --------------------------------------------------------
        # 1. Generate secure candidate token
        # --------------------------------------------------------

        raw_token = secrets.token_urlsafe(32)

        token_hash = hashlib.sha256(
            raw_token.encode("utf-8")
        ).hexdigest()

        # --------------------------------------------------------
        # 2. Calculate expiry
        # --------------------------------------------------------

        expires_at = (
            datetime.utcnow()
            + timedelta(
                days=settings.APPLICATION_INVITATION_EXPIRY_DAYS
            )
        )

        # --------------------------------------------------------
        # 3. Create database invitation
        #
        # reference_id is generated by PostgreSQL.
        # sent_by_employee_id comes ONLY from JWT.
        # --------------------------------------------------------

        invitation = ApplicationInvitation(
            candidate_email=str(
                request.candidate_email
            ),
            token_hash=token_hash,
            sent_by_employee_id=sent_by_employee_id,
            status=ApplicationInvitationStatus.PENDING.value,
            expires_at=expires_at,
        )

        try:
            self.repository.create(invitation)

            # PostgreSQL-generated ID/reference_id
            # become available after flush.
            self.session.flush()

            # ----------------------------------------------------
            # 4. Generate candidate application URL
            #
            # IMPORTANT:
            # Employee ID/reference ID is NOT exposed here.
            # ----------------------------------------------------

            application_link = (
                f"{settings.FRONTEND_BASE_URL.rstrip('/')}"
                f"/application/{raw_token}"
            )

            # ----------------------------------------------------
            # 5. Resolve email template
            #
            # Backend default is used when subject/message
            # are missing or blank.
            #
            # If employee edited them, edited values are used.
            # ----------------------------------------------------

            template = self.get_email_template()

            subject = (
                request.subject.strip()
                if request.subject
                else template.subject
            )

            message = (
                request.message.strip()
                if request.message
                else template.message
            )

            # ----------------------------------------------------
            # 6. Replace application link
            # ----------------------------------------------------

            body = message.replace(
                "{{APPLICATION_LINK}}",
                application_link,
            )

            body = body.replace(
                "{{EXPIRY_DAYS}}",
                str(
                    settings.APPLICATION_INVITATION_EXPIRY_DAYS
                ),
            )

            # ----------------------------------------------------
            # 7. Send email
            # ----------------------------------------------------

            await self.email_service.send_email(
                recipient=str(
                    request.candidate_email
                ),
                subject=subject,
                body=body,
            )

            # ----------------------------------------------------
            # 8. Commit only after successful email
            # ----------------------------------------------------

            self.session.commit()

        except Exception:
            self.session.rollback()
            raise

        return ApplicationInvitationResponse(
            success=True,
            message="Application invitation sent successfully.",
            reference_id=int(
                invitation.reference_id
            ),
            application_link=application_link,
        )

    # ============================================================
    # VALIDATE TOKEN
    # ============================================================

    def validate_token(
        self,
        raw_token: str,
    ) -> ApplicationInvitationValidationResponse:

        if not raw_token or not raw_token.strip():
            return ApplicationInvitationValidationResponse(
                valid=False
            )

        token_hash = hashlib.sha256(
            raw_token.encode("utf-8")
        ).hexdigest()

        invitation = (
            self.repository.get_by_token_hash(
                token_hash
            )
        )

        if invitation is None:
            return ApplicationInvitationValidationResponse(
                valid=False
            )

        if invitation.status in (
            ApplicationInvitationStatus.USED.value,
            ApplicationInvitationStatus.CANCELLED.value,
        ):
            return ApplicationInvitationValidationResponse(
                valid=False
            )

        if datetime.utcnow() > invitation.expires_at:

            self.repository.update_status(
                invitation,
                ApplicationInvitationStatus.EXPIRED,
            )

            self.session.commit()

            return ApplicationInvitationValidationResponse(
                valid=False
            )

        return ApplicationInvitationValidationResponse(
            valid=True,
            candidate_email=invitation.candidate_email,
            status=invitation.status,
        )

    # ============================================================
    # USE INVITATION
    # ============================================================

    def use_invitation(
        self,
        raw_token: str,
    ) -> bool:

        if not raw_token or not raw_token.strip():
            return False

        token_hash = hashlib.sha256(
            raw_token.encode("utf-8")
        ).hexdigest()

        invitation = (
            self.repository.get_by_token_hash(
                token_hash
            )
        )

        if invitation is None:
            return False

        if (
            invitation.status
            != ApplicationInvitationStatus.PENDING.value
        ):
            return False

        if datetime.utcnow() > invitation.expires_at:

            self.repository.update_status(
                invitation,
                ApplicationInvitationStatus.EXPIRED,
            )

            self.session.commit()

            return False

        self.repository.mark_as_used(
            invitation
        )

        self.session.commit()

        return True